# ============================================================
# WHAT THE DATABASE ACTUALLY STORED FOR A GRN.
#
# The screen can show one number and the row can hold another -
# that is the whole point of the client issue this serves. A
# toast, a printed GRN and a grid are all renderings; this is the
# record. So the test compares against THIS, not against another
# view of the same screen.
#
# Read-only throughout: db_helpers refuses anything but SELECT.
#
# WHERE THE PRECISION GOES
# ------------------------
#   PurchaseReceiveLine.Price        decimal(18,6)   <- 6 decimals
#   PurchaseReceiveLine.TotalAmount  numeric (18,2)  <- 2
#   PurchaseReceive.ItemTotalAmount  numeric (18,2)  <- 2
#   PurchaseReceive.TotalVatAmount   decimal (18,2)  <- 2
#   PurchaseReceive.NetAmount        numeric (18,2)  <- 2
#
# A rate can therefore be stored as 29.985 while every total
# built from it is rounded to 2 places. Whether the totals are
# computed from the full-precision price or from a rounded one is
# exactly what decides if the saved amount matches the invoice.
# ============================================================

import os
import sys

_FRAMEWORK_DIR = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
if _FRAMEWORK_DIR not in sys.path:
    sys.path.insert(0, _FRAMEWORK_DIR)


def _db():
    import db_helpers
    return db_helpers


def header_by_challan(challan_no):
    """The saved GRN header, found by the challan number the test typed.

    Challan is what the test controls, so it is the reliable handle -
    the GRN code is generated by the server and is not known up front.
    """
    rows = _db()._query("""
        SELECT TOP 1
            PurchaseReceiveId, PurchaseReceiveCode, PurchaseReceiveGrn, ChallanId,
            SupplierName, ReceiveDate,
            TotalQuantity, ItemTotalAmount, TotalVatAmount,
            HeaderDiscount, HeaderDiscountPercentage, NetDiscount, TotalLineDiscount,
            NetAmount, PendingAmount, PaidAmount, SupplierNetAmount,
            numLaborCharge, numDeliveryCharge, numOtherCharge,
            isInclusive, isAmountDriven, isActive, ActionTime
        FROM dbo.PurchaseReceive
        WHERE ChallanId = ?
        ORDER BY PurchaseReceiveId DESC
    """, [str(challan_no)])
    return rows[0] if rows else None


def lines_of(purchase_receive_id):
    """Every line of that GRN, with the price at full stored precision."""
    return _db()._query("""
        SELECT Id, ItemId, ItemName, Quantity, Price, TotalAmount,
               VatParcentage, VatAmount, LineDiscount, NetAmount,
               HeaderDiscountProportion, SellingPrice
        FROM dbo.PurchaseReceiveLine
        WHERE PurchaseReceiveId = ?
        ORDER BY Id
    """, [int(purchase_receive_id)])


def as_totals(header):
    """The header in the same words the screen uses, so the two can be
    put side by side without the reader translating column names."""
    if not header:
        return {}
    return {
        "Total Qty": float(header["TotalQuantity"] or 0),
        "Item Total": float(header["ItemTotalAmount"] or 0),
        "Total VAT": float(header["TotalVatAmount"] or 0),
        "Discount": float(header["HeaderDiscount"] or 0),
        "Purchase Total": float(header["NetAmount"] or 0),
        "Pending Amount": float(header["PendingAmount"] or 0),
    }


def recompute_from_lines(lines, header_discount=0.0):
    """What the totals WOULD be, computed two ways from the stored lines.

    This is the evidence that separates "the app rounded the rate before
    saving" from "the app stored the rate but rounded the totals":

      full_precision : sum(Quantity * Price)           using Price as stored (6 dp)
      rounded_rate   : sum(Quantity * round(Price, 2)) as the screen displays it

    If the stored header matches `rounded_rate` and the invoice matches
    `full_precision`, the loss happened at the rate, not at the total.
    """
    full = 0.0
    rounded = 0.0
    vat_full = 0.0
    for line in lines:
        qty = float(line["Quantity"] or 0)
        price = float(line["Price"] or 0)
        vat_pct = float(line["VatParcentage"] or 0)
        full += qty * price
        rounded += qty * round(price, 2)
        vat_full += qty * price * vat_pct / 100.0
    return {
        "full_precision_item_total": round(full, 2),
        "rounded_rate_item_total": round(rounded, 2),
        "difference": round(full - rounded, 2),
        "full_precision_vat": round(vat_full, 2),
        "net_full_precision": round(full + vat_full - float(header_discount or 0), 2),
    }


def receivable_items(supplier_id, limit=15):
    """Items this supplier can actually be received against.

    The Direct Receive item picker offers nothing until a supplier is
    chosen, and then only that supplier's items - so the list has to be
    drawn the same way or the test types codes the screen will never
    find.

    IsActive matters as much as IsPurchase: an inactive item is skipped
    in silence, which the exe suites in this repo learned the hard way.

    ItemCode is what the picker searches on (not the name), so it is the
    handle the test uses.
    """
    return _db()._query("""
        SELECT TOP (?)
            ItemId, ItemCode, ItemName, UomName,
            ItemCategoryName, ItemSubCategoryName, MinorCategoryName
        FROM dbo.Item
        WHERE SupplierId = ?
          AND IsPurchase = 1
          AND IsActive = 1
          AND ItemCode IS NOT NULL AND ItemCode <> ''
        ORDER BY ItemId DESC
    """, [int(limit), int(supplier_id)])
